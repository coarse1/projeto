package mainEnum;

/**
 * Enumeration of the commands accepted by the application (help, quit,
 * addJourney, findJourney, findJourneyMinStops and removeJourney).
 *
 * Space complexity: O(1) (fixed number of constants).
 */
public enum Commands {
	HELP, QUIT, ADDJOURNEY, FINDJOURNEY, FINDJOURNEYMINSTOPS, REMOVEJOURNEY;
}
